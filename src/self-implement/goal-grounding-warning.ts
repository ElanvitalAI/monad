/**
 * ⛔⭐⭐⭐ **「코드 후보 0」이 «침묵»하지 않게 한다** (43차 · 2026-08-04)
 *
 * ## ✅ 확실한 것 — 이것만이 이 모듈의 근거다
 * ```
 * 코드 후보가 0 이어도 «참조 지식»(스킬·기억·문서·pty)은 그대로 나온다.
 * ⇒ 산출 줄이  `grounded: 코드 후보 0 · 참조 지식 9건`  이라 「접지됐다」처럼 읽힌다.
 * ⇒ 그 골은 NOT-GROUNDED 로 서고 `--lint` 가 `ERROR [traced-path] … Evidence unavailable` 를 낸다.
 * ⇒ 발사가 막히는데, 사람은 그 이유를 산출 줄에서 «못 읽는다».
 * ```
 * ⇒ ⭐ 근거 = `R-GIT11`(*거부는 산출을 남길 때만 정당하다*)의 **반대편** — 여기서 문제는 거부가 아니라
 *   ***침묵하는 「0」***이다. 「0」이 「이 코드베이스엔 근거가 없다」로 읽히는 것을 막는다.
 *
 * ## ⛔⭐⭐⭐ 초판이 틀렸던 것 — **「링크된 worktree 면 «항상» 0」이 반증됐다**
 * ```
 * 초판 주장    링크된 worktree ⇒ 코드 후보 0  (그래서 트리를 «트리거 조건»에 넣었다)
 * ⛔ 반증 ①    상대 세션이 같은 조건에서 «2» 를 냈다(TRACED PATHS 에 파일 «내용»까지 실렸다)
 * ⛔ 반증 ②    ask 를 «고정»하고 트리만 바꾼 실측:   main «3»  ·  main-worktree «3»   ← 같다
 * ⇒ ***반증된 것은 「«항상» 0」이다.*** ⛔ 이것이 «트리가 전혀 무관하다» 를 증명하지는 «않는다» —
 *   각 칸이 표본 1 이고 대조는 한 쌍뿐이다. ⇒ 트리도 «배제되지 않은 후보»로 남는다(`R-CLM5`).
 *   ⊕ 초판 표는 트리와 `ask` 를 «같이» 바꾼 교란된 표였다 — 「트리만 바꿨다」가 거짓이었다.
 * ```
 * ⇒ 🩹 그래서 **트리 조건을 트리거에서 지웠다.** 원인을 모르는 채 「원인처럼 보이는 것」을 문면에 실으면
 *   ***읽는 사람이 틀린 원인을 좇는다 — 침묵보다 나쁠 수 있다.***
 * ⊕ 전 표본과 미해결(대상이 없는 트리에서 1, 있는 트리에서 0 이 나온 «역전»)은
 *   `내부 문서 `ISSUES`` `GOAL-T56`(**open**).
 *
 * ## ⚠️ 이력 — ⛔ **아래 옛 이름의 파일은 «이 저장소에 없다»**(현재 파일은 이 파일 하나다)
 * ```
 * 옛 이름   src/self-implement/goal-grounding-tree.ts   ⛔ 없음(개명됨)
 * 현재      src/self-implement/goal-grounding-warning.ts
 * 왜        트리 축을 «철회»하고도 파일명이 그것을 «기능 정체성»처럼 계속 달고 있었다.
 * ```
 * ⇒ ⭐ 철회는 코드·API·주석·색인·테스트뿐 아니라 ***이름***까지 훑어야 한다.
 *
 * ## ⛔ 이 모듈이 «안» 하는 것 (과장하지 않는다)
 * ```
 * ⛔ 저작을 막지 않는다     — 참조 지식만으로 쓸 수 있는 골이 있다
 * ⛔ 원인을 단정하지 않는다 — ask·대상 경로는 여전히 후보다. 다만 완료 선언 없이 끝난 관측은
 *   `stopReason`이 `goal_complete`가 아닐 때만 셋째 후보로 적어, 실측된 종료 이유를 그 자리에서 보인다.
 * ⛔ 접지를 고치지 않는다   — 별도 골이다
 * ```
 */

interface GroundingWarningInput {
  /**
   * 저작 산출의 코드 후보 수.
   * ⛔ **못 잰 경우는 `undefined` 로 준다** — 부르는 쪽에서 `?? 0` 으로 바꿔 넘기면
   * 「안 쟀다」가 「0 으로 관측됐다」가 되어 **거짓 경고**가 나간다(무인 리뷰 must-fix · `#6980`).
   */
  codeCandidates: number | undefined;
  /** 참조 지식(스킬·기억·문서·pty) 합. 「접지된 것처럼 보이는」 이유라 문면에 싣는다. */
  referenceFacts: number;
  /** Persistent grounding loop의 관측 종료 이유. 못 쟀으면 생략하며 `goalComplete`는 중복이라 싣지 않는다. */
  stopReason?: string;
}

/**
 * 사람이 읽는 경고 한 줄. 낼 이유가 없으면 `null`.
 *
 * ⭐ 트리거는 ***「코드 후보가 «정확히» 0」*** 하나다 — 트리 조건은 반증돼서 지웠다(헤더).
 * ⛔ `> 0` 이 아니라 `!== 0` 으로 본다 — `> 0` 이면 음수·`NaN` 에도 경고가 나가고,
 *   그건 「셀 수 없었다」를 「0 이다」로 읽는 것이다(`R-GIT3`).
 * ⛔ `undefined`(못 쟀다)에는 **침묵한다** — 「모른다」를 「0」으로 바꾸지 않는다.
 */
export function groundingWarning(input: GroundingWarningInput): string | null {
  // ⭐ `undefined`(못 쟀다)도 이 한 줄이 «같이» 막는다 — `undefined !== 0` 이 참이라서다.
  //   ⛔ 초판은 `undefined` 전용 가드를 따로 뒀는데 **뮤테이션이 안 물렸다**(지워도 5 pass) —
  //     즉 근거가 없는 줄이었다. 계약은 테스트가 지키고, 코드는 «한 줄»로 둔다.
  if (input.codeCandidates !== 0) return null;
  const unfinishedLoopCause = input.stopReason && input.stopReason !== 'goal_complete'
    ? ` · 완료 선언 없이 끝난 접지 루프(stopReason: ${input.stopReason})`
    : '';
  return '⛔ 코드 후보가 «0 으로 관측»됐다 — 「이 코드베이스에 근거가 없다」는 뜻이 «아닐 수 있다».'
    + ` 참조 지식 ${input.referenceFacts}건은 나왔으니 산출이 「접지됐다」처럼 읽히지만,`
    + ' 이대로 두면 골이 NOT-GROUNDED 로 서고 --lint 가 ERROR [traced-path] 를 내 «발사가 막힌다».'
    + ` ⚠️ 원인은 아직 안 갈렸다 — 후보: ask 가 얇다 · 대상 경로가 이 트리에 없다${unfinishedLoopCause}(GOAL-T56).`;
}
